const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const build=fs.readFileSync(path.join(root,'build.py'),'utf8');
const release=fs.readFileSync(path.join(root,'src/release.js'),'utf8');
const template=fs.readFileSync(path.join(root,'index.template.html'),'utf8');
const v015=fs.readFileSync(path.join(root,'src/v015polish.js'),'utf8');
const v016=fs.readFileSync(path.join(root,'src/v016polish.js'),'utf8');
const v017game=fs.readFileSync(path.join(root,'src/v017gameplay.js'),'utf8');
const v017polish=fs.readFileSync(path.join(root,'src/v017polish.js'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
assert(build.includes("VERSION='0.17'"),'build version must be v0.17');
assert(build.includes("Neon-Descent-v{VERSION}.html"),'build must emit a versioned standalone filename');
for(const layer of ['v015polish','v016polish','v017gen','v017pre','v017camera','v017gameplay','v017polish'])assert(build.includes(`'${layer}'`),`build must bundle ${layer}`);
assert(release.includes("const VERSION='__NEON_VERSION__'"),'release HUD/title must use the build-injected version');
for(const marker of ['V014PRE','V013POLISH','V014POLISH','V015POLISH','V016POLISH','V017GEN','V017PRE','V017CAMERA','V017GAMEPLAY','V017POLISH','RELEASE'])assert(template.includes(`/*${marker}*/`),`standalone template must load ${marker}`);
assert(template.indexOf('/*V017GEN*/')<template.indexOf('/*GAME*/'),'v0.17 generation repair must load before Game captures generate');
assert(template.indexOf('/*V017PRE*/')<template.indexOf('/*POLISH*/'),'v0.17 camera migration must load before settings polish');
assert(template.indexOf('/*V017POLISH*/')>template.indexOf('/*V016POLISH*/'),'v0.17 debug page must wrap the v0.16 pause computer');
assert(v015.includes('drawCableClimber'),'v0.15 must keep a cable-specific climb pose');
assert(v016.includes('drawGripClinger'),'v0.16 must keep a Magnetic Grip-specific wall pose');
assert(v017game.includes('damageTrap')&&v017game.includes('lineClear'),'v0.17 must retain destructible trap and LOS fixes');
assert(v017polish.includes('nd-debug-tab'),'v0.17 must retain the temporary pause DEBUG category');
assert.equal(pkg.version,'0.17.0','package version should match v0.17 release');
console.log('PASS v0.17 artifact, version source, camera/combat/generation layers, and temporary DEBUG pause page are synchronized');
